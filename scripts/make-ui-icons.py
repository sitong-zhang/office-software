#!/usr/bin/env python3
"""Rasterize the pinned Lucide SVGs into tinted interface icons."""

import subprocess
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "app" / "branding" / "third-party" / "lucide" / "icons"
OUT = ROOT / "app" / "ui" / "icons"
OUT.mkdir(parents=True, exist_ok=True)

VARIANTS = [
    ("dark", (16, 32, 26)),
    ("cream", (244, 241, 232)),
    ("green", (31, 92, 70)),
    ("muted", (107, 114, 105)),
    ("soft", (156, 170, 160)),
]

ICONS = [
    ("house", "HOUSE"),
    ("file-plus", "FILE_PLUS"),
    ("folder-open", "FOLDER_OPEN"),
    ("clock-3", "CLOCK"),
    ("megaphone", "MEGAPHONE"),
    ("settings", "SETTINGS"),
    ("file-text", "FILE_TEXT"),
    ("table-2", "TABLE"),
    ("presentation", "PRESENTATION"),
    ("shapes", "SHAPES"),
    ("download", "DOWNLOAD"),
    ("circle-check", "CHECK_CIRCLE"),
    ("shield-check", "SHIELD_CHECK"),
    ("x", "CLOSE"),
    ("minus", "MINIMIZE"),
    ("chevron-right", "CHEVRON_RIGHT"),
    ("refresh-cw", "REFRESH"),
    ("trash", "TRASH"),
    ("info", "INFO"),
    ("arrow-right", "ARROW_RIGHT"),
    ("sparkles", "SPARKLES"),
    ("hard-drive", "HARD_DRIVE"),
    ("bell", "BELL"),
    ("external-link", "EXTERNAL_LINK"),
]


def render(name, size=64):
    svg = SOURCE / f"{name}.svg"
    if not svg.exists():
        raise SystemExit(f"missing icon source: {svg}")
    with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as handle:
        raster = Path(handle.name)
    try:
        subprocess.run(
            [
                "rsvg-convert",
                "-w",
                str(size),
                "-h",
                str(size),
                "-f",
                "png",
                str(svg),
                "-o",
                str(raster),
            ],
            check=True,
            capture_output=True,
        )
        glyph = Image.open(raster).convert("RGBA")
        glyph.load()
    finally:
        raster.unlink(missing_ok=True)
    return glyph


def main():
    header = [
        "// Generated by scripts/make-ui-icons.py. Do not edit by hand.",
        "#pragma once",
        "",
        "enum UiIconVariant {",
        "  UI_VARIANT_DARK = 0,",
        "  UI_VARIANT_CREAM = 1,",
        "  UI_VARIANT_GREEN = 2,",
        "  UI_VARIANT_MUTED = 3,",
        "  UI_VARIANT_SOFT = 4,",
        "};",
        "",
    ]
    resources = ["// Generated by scripts/make-ui-icons.py. Do not edit by hand.", ""]
    base = 200
    for name, macro in ICONS:
        header.append(f"#define UI_ICON_{macro} {base}")
        glyph = render(name)
        alpha = glyph.getchannel("A")
        for offset, (variant, color) in enumerate(VARIANTS):
            tinted = Image.new("RGBA", glyph.size, tuple(color) + (0,))
            tinted.putalpha(alpha)
            filename = f"{name}-{variant}.png"
            tinted.save(OUT / filename)
            resources.append(f'{base + offset} RCDATA "app/ui/icons/{filename}"')
        base += len(VARIANTS)
    (ROOT / "app" / "ui" / "icons.h").write_text("\n".join(header) + "\n", encoding="utf-8")
    (ROOT / "app" / "ui" / "icons.rc").write_text("\n".join(resources) + "\n", encoding="utf-8")
    print(f"ui icons written: {len(ICONS)} icons, {len(ICONS) * len(VARIANTS)} files")


if __name__ == "__main__":
    main()
